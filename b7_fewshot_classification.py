import kagglehub
import pandas as pd
import glob
import os

path = kagglehub.dataset_download(
    "shashwatwork/consume-complaints-dataset-fo-nlp"
)

csv_file = glob.glob(path + "/**/*.csv", recursive=True)[0]

df = pd.read_csv(csv_file, low_memory=False)

print("Dataset downloaded!")
print(df.shape)
print(df.head())

# Select required columns
df = df[[
    "narrative",
    "product"
]].dropna()

df.columns = ["complaint", "category"]

# Remove duplicate complaints
df = df.drop_duplicates(subset="complaint")

# Select top 5 categories
top_categories = df["category"].value_counts().head(5).index

df = df[df["category"].isin(top_categories)]

# Select up to 1000 complaints per category
df = df.groupby("category", group_keys=False).apply(
    lambda x: x.sample(min(len(x), 1000), random_state=42)
)

df = df.reset_index(drop=True)

print("Final dataset:", df.shape)
print(df["category"].value_counts())

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    df["complaint"],
    df["category"],
    test_size=0.2,
    random_state=42,
    stratify=df["category"]
)

print("Training:", len(X_train))
print("Testing:", len(X_test))

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score

vectorizer = TfidfVectorizer(
    max_features=5000,
    stop_words="english"
)

X_train_vec = vectorizer.fit_transform(X_train)
X_test_vec = vectorizer.transform(X_test)

model = LogisticRegression(max_iter=1000)

model.fit(X_train_vec, y_train)

baseline_predictions = model.predict(X_test_vec)

print("Baseline Accuracy:",
      accuracy_score(y_test, baseline_predictions))

print("Baseline F1 Score:",
      f1_score(y_test, baseline_predictions, average="macro"))

import torch
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

model_name = "google/flan-t5-base"

device = "cuda" if torch.cuda.is_available() else "cpu"

tokenizer = AutoTokenizer.from_pretrained(model_name)

llm = AutoModelForSeq2SeqLM.from_pretrained(
    model_name
).to(device)

categories = list(top_categories)

print("GenAI model loaded!")
print("Device:", device)

# Select one example from each category
examples = df.groupby("category").first().reset_index()

def classify(complaint, few_shot=False):

    prompt = "Classify this consumer complaint.\n"
    prompt += "Choose only from these categories:\n"
    prompt += ", ".join(categories) + "\n"

    if few_shot:
        prompt += "\nExamples:\n"

        for _, row in examples.iterrows():
            prompt += (
                f"Complaint: {row['complaint'][:100]}\n"
                f"Category: {row['category']}\n"
            )

    prompt += f"\nComplaint: {complaint[:300]}\n"
    prompt += "Return only the correct category."

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=512
    ).to(device)

    with torch.no_grad():
        output = llm.generate(
            **inputs,
            max_new_tokens=30
        )

    answer = tokenizer.decode(
        output[0],
        skip_special_tokens=True
    ).strip()

    # Match the generated answer to an available category
    for category in categories:
        if answer.lower() == category.lower():
            return category

    for category in sorted(categories, key=len, reverse=True):
        if category.lower() in answer.lower():
            return category

    return "Unclassified"


print("Classification functions ready!")

from tqdm.auto import tqdm

X_sample = X_test.iloc[:50].reset_index(drop=True)
y_sample = y_test.iloc[:50].reset_index(drop=True)

zero_predictions = []
few_predictions = []

for complaint in tqdm(X_sample):

    zero_predictions.append(
        classify(complaint, few_shot=False)
    )

    few_predictions.append(
        classify(complaint, few_shot=True)
    )

print("Classification completed!")

from sklearn.metrics import classification_report, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns

baseline_sample = model.predict(
    vectorizer.transform(X_sample)
)

results = pd.DataFrame({
    "Model": [
        "TF-IDF + Logistic Regression",
        "Zero-shot LLM",
        "Few-shot LLM"
    ],

    "Accuracy": [
        accuracy_score(y_sample, baseline_sample),
        accuracy_score(y_sample, zero_predictions),
        accuracy_score(y_sample, few_predictions)
    ],

    "Macro F1": [
        f1_score(y_sample, baseline_sample, average="macro"),
        f1_score(y_sample, zero_predictions, average="macro"),
        f1_score(y_sample, few_predictions, average="macro")
    ]
})

display(results)

# Performance graph
results.set_index("Model").plot(
    kind="bar",
    figsize=(9, 5),
    ylim=(0, 1)
)

plt.title("Comparison of Three Classification Models")
plt.ylabel("Score")
plt.xticks(rotation=15)
plt.tight_layout()
plt.show()

# Confusion matrix for few-shot model
labels = categories + ["Unclassified"]

sns.heatmap(
    confusion_matrix(
        y_sample,
        few_predictions,
        labels=labels
    ),
    annot=True,
    fmt="d",
    xticklabels=labels,
    yticklabels=labels
)

plt.title("Few-Shot Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

print("\nFew-shot classification report:")
print(classification_report(
    y_sample,
    few_predictions,
    labels=labels,
    zero_division=0
))

